"""Run a local, single-validator Hyperledger Besu (QBFT) chain for the Besu ledger
adapter (HC-194, ADR-0007). For development and demos only.

    python ledger/dev_chain.py            # set up on first run, then start Besu

Needs the `besu` command (Besu 26.x, Java 21) on PATH, or its path in BESU. On first
run it writes ledger/.chain/ (gitignored, never commit it):

- `anchor.key`: a new key for the Governance Node's ledger account, the account that
  deploys the AuditAnchor contract and is the only one allowed to anchor;
- `network/`: the genesis file and the validator's node key, generated by
  `besu operator generate-blockchain-config` from qbft-config.json; the anchor account
  is funded in the genesis, although the chain's gas price is zero anyway.

Besu then serves JSON-RPC on 127.0.0.1:8545 only, with peer-to-peer and discovery off.
Delete ledger/.chain/ to start a new chain. One validator run by the Governance Node
gives no assurance independent of it; see ADR-0007.
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from eth_account import Account

HERE = Path(__file__).resolve().parent
CHAIN = HERE / ".chain"
ANCHOR_KEY = CHAIN / "anchor.key"
NETWORK = CHAIN / "network"
NODE = CHAIN / "node"
RPC_PORT = 8545


def _besu() -> str:
    besu = os.environ.get("BESU") or shutil.which("besu")
    if not besu:
        sys.exit("besu not found: put it on PATH or set BESU to its path")
    return besu


def set_up(besu: str) -> None:
    CHAIN.mkdir(exist_ok=True)
    if not ANCHOR_KEY.exists():
        ANCHOR_KEY.write_text(Account.create().key.hex(), encoding="utf-8")
    anchor = Account.from_key(ANCHOR_KEY.read_text(encoding="utf-8").strip())
    config = json.loads((HERE / "qbft-config.json").read_text(encoding="utf-8"))
    config["genesis"]["alloc"] = {anchor.address: {"balance": hex(10**24)}}
    generated = CHAIN / "qbft-config.json"
    generated.write_text(json.dumps(config, indent=2), encoding="utf-8")
    subprocess.run(
        [
            besu,
            "operator",
            "generate-blockchain-config",
            f"--config-file={generated}",
            f"--to={NETWORK}",
            "--private-key-file-name=key",
        ],
        check=True,
    )
    (validator,) = (NETWORK / "keys").iterdir()
    NODE.mkdir()
    shutil.copy(validator / "key", NODE / "key")
    print(f"Anchor account {anchor.address}; key in {ANCHOR_KEY}")


def main() -> None:
    besu = _besu()
    if not NETWORK.exists():
        set_up(besu)
    print(
        "Start the Governance Node with GOVERNANCE_LEDGER=besu and "
        f"GOVERNANCE_LEDGER_KEY_FILE={ANCHOR_KEY}"
    )
    subprocess.run(
        [
            besu,
            f"--data-path={NODE}",
            f"--genesis-file={NETWORK / 'genesis.json'}",
            "--min-gas-price=0",
            "--p2p-enabled=false",
            "--discovery-enabled=false",
            "--rpc-http-enabled",
            "--rpc-http-host=127.0.0.1",
            f"--rpc-http-port={RPC_PORT}",
            "--rpc-http-api=ETH,NET,WEB3,QBFT",
            "--host-allowlist=localhost,127.0.0.1",
        ],
        check=True,
    )


if __name__ == "__main__":
    main()
